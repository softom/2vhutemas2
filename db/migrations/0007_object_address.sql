-- 0007: почтовый адрес объекта.
--
-- При первой же работе с формой выяснилось, что адреса объекта в профиле нет:
-- есть только город и страна. Для зданий и музеев адрес нужен и в карточке,
-- и при переносе данных старого контура.
--
-- Адрес хранится как есть, одной строкой: разбор на улицу, дом и индекс
-- у разных стран разный, а исходная запись источника важнее унификации.

alter table app.object_profile add column if not exists address text;

comment on column app.object_profile.address is
    'Почтовый адрес одной строкой, как указан источником';
