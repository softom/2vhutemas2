-- «Откуда цифра»: данные, расчёт, оценка.
--
-- Пользователь 2026-10-14: «Давай расширим таблицу экспликации параметром —
-- данные, расчёт, оценка, чтобы иметь понимание, откуда взяли цифру».
-- Колонка «Основание площади» (0041) уже несла этот смысл; её название и
-- варианты приводятся к словам пользователя. Коды вариантов прежние —
-- строки программ ссылаются на варианты по идентификатору и не меняются.

update app.parameters
   set title_ru = 'Откуда цифра',
       definition = 'Данные — площадь взята из документа как есть (в том числе с пересчётом единиц, например из квадратных футов). '
                 || 'Расчёт — посчитана редакцией по данным документа: по габаритам, по числу мест и размеру места, по сумме строк. '
                 || 'Оценка — приближённо, без прямых данных в документе. Нет данных — площадь неизвестна, строка фиксирует состав.'
 where code = 'program_area_basis';

update app.parameter_options o
   set title_ru = x.title
  from (values ('document', 'данные'),
               ('dimensions', 'расчёт'),
               ('estimate', 'оценка'),
               ('unknown', 'нет данных')) as x(code, title)
 where o.code = x.code
   and o.parameter_id = (select id from app.parameters where code = 'program_area_basis');
