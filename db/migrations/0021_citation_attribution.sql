-- Цитирование в учебных целях: изображение публично только со ссылками (Р-67).
--
-- Решение пользователя 2026-09-27: «чужие» изображения показываем по праву
-- цитирования в учебных целях, а оно требует указания автора и источника.
-- Значит публичным может быть только тот файл, у которого есть и то, и другое.
--
-- Колонок не добавляем: автор, правообладатель, источник, подпись источника и
-- место хранения в `media_assets` уже есть — не заполнены. Миграция закрывает
-- от посторонних то, что нечем подписать; после заполнения полей редактор
-- возвращает файл в публичные обычной правкой.
--
-- Записи это не трогает: закрывается файл, а не карточка.

begin;

update app.media_assets
   set visibility = 'private',
       updated_at = now()
 where archived_at is null
   and visibility = 'public'
   and not (coalesce(nullif(author, ''), nullif(credit, '')) is not null
        and coalesce(nullif(source_url, ''), nullif(original_caption, ''),
                     nullif(holder, '')) is not null);

commit;
