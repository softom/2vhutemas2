-- Материалы в работе — папки в Dropbox (0052).
--
-- Решение пользователя 2026-10-15: материалы складываются в Dropbox, в папку
-- 2VHUTEMAS: ЧТО/ПРОЕКТЫ и КТО/ЛЮДИ, папка записи — «<тип>_<название>»
-- (например «арх_объекты_Национальный театр Тайчжуна»). Кнопка «Обновить
-- файловую структуру» на сайте досоздаёт папки новым записям и читает опись
-- через API Dropbox. Dropbox отдаёт свою контрольную сумму (content_hash),
-- а не sha256 — для неё отдельная колонка; sha256 по-прежнему присылает
-- локальный скрипт, по нему узнаются файлы медиатеки.

alter table app.material_files add column content_hash text;
comment on column app.material_files.content_hash is
  'Контрольная сумма Dropbox (content_hash) — из описи, снятой сервером через API Dropbox.';
